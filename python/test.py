# Ecrire un algorithme qui demande un nombre à
#  l’utilisateur, et l’informe ensuite si ce nombre est
#   positif ou négatif (on laisse de côté le cas où 
#   le nombre vaut zéro).

nombre = input("entrer un nombre: ")

if nombre > 0:
    print("Le nombre est positif")
else:
    print("Le nombre est negatif")